import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildExam, grade, scorePct, updateRevision, shuffle } from '../src/features/exam/logic';
const pool = JSON.parse(readFileSync('public/data/questions/data-management.json', 'utf8'));
let seed = 1; const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
const ex = buildExam(pool, 10, rnd);
assert.equal(ex.length, 10); assert.equal(new Set(ex.map(i => i.q.id)).size, 10);
assert.ok(ex.every(i => [...i.order].sort().join('') === 'ABCD'));
assert.equal(buildExam(pool, 999).length, pool.length, 'count capped at pool size');
assert.equal(shuffle([1, 2, 3, 4, 5]).sort().join(''), '12345');
const sel: any = {}; ex.slice(0, 4).forEach(i => (sel[i.q.id] = i.q.correctAnswer)); sel[ex[4].q.id] = ex[4].q.correctAnswer === 'A' ? 'B' : 'A';
const ans = grade(ex, sel, new Set([ex[0].q.id]));
assert.equal(ans.filter(a => a.correct).length, 4); assert.equal(ans[5].selected, null); assert.equal(ans[0].flagged, true);
assert.equal(scorePct(ans), 40); assert.equal(scorePct([]), 0);
const now = new Date('2026-01-01T00:00:00Z');
let rev = updateRevision([], ans, now);
assert.equal(rev.find(r => r.questionId === ex[0].q.id)!.box, 0);
rev = updateRevision(rev, ans, now);
assert.equal(rev.find(r => r.questionId === ex[0].q.id)!.box, 1, 'correct twice advances box');
assert.equal(rev.find(r => r.questionId === ex[4].q.id)!.box, 0, 'wrong stays box 0');
assert.equal(rev.find(r => r.questionId === ex[0].q.id)!.dueAt, '2026-01-03T00:00:00.000Z');
console.log('exam logic tests passed');
